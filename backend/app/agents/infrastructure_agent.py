"""
InfrastructureAgent — Docker-only artifact generator (structured pipeline + LLM fallback).

Architecture (Phase 1 — Structured Constrained Generation):

  Primary path:
    project_context
    → BlueprintSelector      (picks python_fastapi / spring_boot / node_express / generic)
    → ArtifactSectionGenerator (one batched LLM call fills section variables)
    → ArtifactAssembler      (deterministic template rendering + ordering)
    → DockerfileValidator    (section-mapped correctness + security check)
    → Dockerfile             (structured, correct, section-traceable)

  Fallback path (on structured pipeline failure):
    → Existing ReAct loop (LLM generates entire artifact)
    → Existing fallback artifact builder (deterministic, no LLM)

All other Docker artifacts (dockerignore, docker-compose, .env.example) continue
to be generated by the existing ReAct loop — the structured pipeline targets
the Dockerfile only in Phase 1.

Public interface (run() signature and return dict shape) is fully preserved.
New output keys added without breaking callers:
  - ``infrastructure_generation``  — full structured pipeline trace
  - ``react_iterations``           — existing field, preserved
  - ``validation_summary``         — existing field, preserved
"""
from __future__ import annotations

import logging
from typing import Any, Callable, Dict, List, Optional

from backend.app.agents.base_agent import EnhancedBaseAgent
from backend.app.services.artifact_generation.pipeline import StructuredDockerfileGenerator
from backend.app.services.cicd.artifact_contract_service import ArtifactContractService
from backend.app.services.artifact_generation.validators.docker_static_validator import DockerBuildStaticValidator
from backend.app.services.infrastructure.build_context_resolver import BuildContextResolver
from backend.app.services.infrastructure.compose_topology_analyzer import ComposeTopologyAnalyzer
from backend.app.services.infrastructure.dockerfile_healthcheck import normalize_healthcheck
from backend.app.services.infrastructure.infrastructure_artifact_builder_service import (
    InfrastructureArtifactBuilderService,
)
from backend.app.services.infrastructure.infrastructure_context_assembler import InfrastructureContextAssembler
from backend.app.services.infrastructure.infrastructure_context_mapper import InfrastructureContextMapper
from backend.app.services.infrastructure.repository_build_context import BuildStrategyDetector
from backend.app.services.llm.provider_factory import ProviderFactory
from backend.app.services.rag.rag_pipeline_service import RAGPipelineService
from backend.app.services.rag.template_retrieval_service import TemplateRetrievalService

logger = logging.getLogger(__name__)


class InfrastructureAgent(EnhancedBaseAgent):
    """
    Generates Docker artifacts using a two-tier architecture:

    Tier 1 (Primary) — Structured Constrained Generation:
      Blueprint-driven → Section-level LLM → Template rendering → Validated Dockerfile

    Tier 2 (Fallback) — Legacy ReAct Loop:
      Monolithic LLM prompt → Full artifact generation → Validation

    Tier 1 is used for Dockerfile. Tier 2 handles all remaining artifacts
    (dockerignore, docker-compose, .env.example) and serves as a safety net.

    Inherits from EnhancedBaseAgent — gains:
      • self.memory      (AgentMemory)
      • self.validation  (ValidationService)
      • react_loop()     (Reasoning + Action with automatic retries)
    """

    def __init__(self, prompt_template: str):
        super().__init__(name="InfrastructureAgent", max_react_iterations=3)
        self.llm = ProviderFactory.for_agent("InfrastructureAgent")
        self.prompt_template = prompt_template
        self.context_mapper = InfrastructureContextMapper()
        self.artifact_builder = InfrastructureArtifactBuilderService()
        self.artifact_contract = ArtifactContractService()
        self.template_retrieval = TemplateRetrievalService()
        self._rag_pipeline = RAGPipelineService()
        # Infrastructure Context Grounding Layer
        self._compose_analyzer = ComposeTopologyAnalyzer()
        self._build_context_resolver = BuildContextResolver()
        self._context_assembler = InfrastructureContextAssembler()
        # Phase 2: Repository build context detection
        self._strategy_detector = BuildStrategyDetector()
        # Phase 5: Pre-build static validation
        self._static_validator = DockerBuildStaticValidator()
        # Phase 1: Structured constrained generation pipeline
        self._structured_generator = StructuredDockerfileGenerator(
            llm=self.llm,
            rag_pipeline=self._rag_pipeline,
        )

    # ── Public interface ──────────────────────────────────────────────────────

    def run(
        self,
        prompt: str,
        plan: Dict[str, Any],
        infrastructure_context: Optional[Dict[str, Any]] = None,
        approved_artifacts: Optional[List[str]] = None,
    ) -> Dict[str, Any]:
        """
        Generate Docker artifacts for the given prompt and plan.

        PHASE CONTRACT — Docker generation MUST NEVER raise. LLM providers
        (rate-limit / token exhaustion / invalid JSON / fallback-chain failure)
        are treated as *non-fatal*: the structured generator's deterministic
        per-section fallbacks and the template-based artifact builder always
        yield a usable Dockerfile. Only a catastrophic, unexpected error reaches
        the outer guard below, which still returns a minimal safe Dockerfile
        rather than propagating a 500 up the workflow.

        Returns the same dict shape as before, plus:
          - ``infrastructure_generation`` — structured pipeline trace (Phase 1)
          - ``react_iterations``          — number of ReAct iterations used
          - ``validation_summary``        — per-artifact validation results
          - ``used_llm``                  — True if the LLM contributed content
          - ``fallback_used``             — True if any deterministic fallback was used
          - ``generation_mode``           — "llm" | "llm_with_fallback" |
                                            "degraded" | "deterministic" |
                                            "emergency_fallback"
        """
        try:
            return self._run_generation(
                prompt=prompt,
                plan=plan,
                infrastructure_context=infrastructure_context,
                approved_artifacts=approved_artifacts,
            )
        except Exception as exc:  # last-resort safety net — must never propagate
            logger.error(
                "[InfrastructureAgent] Generation pipeline failed unexpectedly "
                "(%s: %s) — emitting deterministic safe Dockerfile so the Docker "
                "phase never breaks the workflow",
                exc.__class__.__name__,
                exc,
                exc_info=True,
            )
            return self._emergency_fallback_response(
                prompt=prompt,
                plan=plan,
                infrastructure_context=infrastructure_context,
                approved_artifacts=approved_artifacts,
                error=exc,
            )

    def _run_generation(
        self,
        prompt: str,
        plan: Dict[str, Any],
        infrastructure_context: Optional[Dict[str, Any]] = None,
        approved_artifacts: Optional[List[str]] = None,
    ) -> Dict[str, Any]:
        """Core generation pipeline. See :meth:`run` for the phase contract."""
        # ── 1. Map context ────────────────────────────────────────────────────
        mapped_context = self.context_mapper.map(
            prompt=prompt,
            plan=plan,
            infrastructure_context=infrastructure_context,
            approved_artifacts=approved_artifacts,
        )

        # ── 1b. Infrastructure Context Grounding Layer ────────────────────────
        # Parse docker-compose topology from infrastructure_context if available
        compose_topology = None
        compose_content = (infrastructure_context or {}).get("docker_compose_content")
        if compose_content:
            try:
                compose_topology = self._compose_analyzer.analyze(compose_content)
                logger.info(
                    "[InfrastructureAgent] Compose topology analyzed: backend=%s mode=%s",
                    compose_topology.backend_service,
                    compose_topology.runtime_mode,
                )
            except Exception as exc:
                logger.warning("[InfrastructureAgent] Compose topology analysis failed: %s", exc)

        # Resolve build context against known repository files
        known_files = (infrastructure_context or {}).get("known_files") or []
        build_context = mapped_context.get("build_context", ".")
        build_context_report = None
        try:
            report = self._build_context_resolver.resolve(
                dockerfile_content="",  # no Dockerfile yet — resolve later in post-gen validation
                build_context=build_context,
                known_files=known_files or None,
            )
            build_context_report = report.to_dict()
        except Exception as exc:
            logger.warning("[InfrastructureAgent] Build context resolution failed: %s", exc)

        # Assemble normalized, topology-aware context
        mapped_context = self._context_assembler.assemble(
            mapped_context=mapped_context,
            compose_topology=compose_topology,
            known_files=known_files or None,
            build_context_report=build_context_report,
        )

        # ── 1c. Repository Build Context (Phase 2) ────────────────────────────
        # Detect strategy AFTER compose topology is available
        try:
            repo_build_ctx = self._strategy_detector.detect(
                known_files=known_files or [],
                mapped_context=mapped_context,
                compose_topology=compose_topology,
            )
            build_artifact_ctx = self._strategy_detector.build_artifact_context(
                repo_ctx=repo_build_ctx,
                mapped_context=mapped_context,
            )
            # Inject into mapped_context so section_generator can use it
            mapped_context["repository_build_context"] = repo_build_ctx.to_dict()
            mapped_context["build_artifact_context"] = build_artifact_ctx.to_dict()
            logger.info(
                "[InfrastructureAgent] Repository build context: strategy=%s context=%s "
                "backend_root=%s copy_prefix=%s",
                repo_build_ctx.docker.strategy if repo_build_ctx.docker else "unknown",
                repo_build_ctx.docker.context_path if repo_build_ctx.docker else ".",
                repo_build_ctx.backend_root,
                (repo_build_ctx.docker.recommended_copy_prefix if repo_build_ctx.docker else None),
            )
        except Exception as exc:
            logger.warning("[InfrastructureAgent] Repository build context detection failed: %s", exc)
            repo_build_ctx = None
            build_artifact_ctx = None

        fallback_artifacts = self.artifact_builder.build_fallback_artifacts(mapped_context)

        # ── 2. Structured Dockerfile generation (Tier 1 — Phase 1) ───────────
        structured_result = None
        structured_dockerfile: Optional[str] = None
        infrastructure_generation: Optional[Dict[str, Any]] = None

        try:
            structured_result = self._structured_generator.generate(
                project_context=mapped_context,
                corrector_feedback=None,
            )
            infrastructure_generation = structured_result.model_dump()

            if structured_result.artifact and not structured_result.has_validation_errors():
                structured_dockerfile = structured_result.artifact

                # ── Phase 5: Post-generation static COPY validation ───────────
                if known_files:
                    build_ctx_path = (
                        (repo_build_ctx.docker.context_path if repo_build_ctx and repo_build_ctx.docker else None)
                        or mapped_context.get("build_context", ".")
                    )
                    try:
                        framework_hint = (
                            ((mapped_context.get("main_service") or {}).get("framework"))
                            or (structured_result.generation_metadata or {}).get("framework")
                            or ""
                        )
                        static_val = self._static_validator.validate(
                            dockerfile_content=structured_dockerfile,
                            build_context=build_ctx_path,
                            known_files=known_files,
                            framework=framework_hint,
                        )
                        infrastructure_generation = infrastructure_generation or {}
                        infrastructure_generation["static_validation"] = static_val.to_dict()
                        if not static_val.valid:
                            logger.warning(
                                "[InfrastructureAgent] Static COPY validation found %d issue(s) "
                                "in generated Dockerfile — these may cause build failures:",
                                len(static_val.issues),
                            )
                            for issue in static_val.issues:
                                logger.warning(
                                    "[InfrastructureAgent]   COPY mismatch: %s → fix: %s",
                                    issue.message,
                                    issue.suggested_fix or "no suggestion available",
                                )
                    except Exception as exc:
                        logger.warning("[InfrastructureAgent] Static validation error: %s", exc)

                logger.info(
                    "[InfrastructureAgent] Structured pipeline succeeded — "
                    "blueprint=%s sections=%d fallbacks=%d",
                    structured_result.blueprint_used,
                    len(structured_result.sections),
                    structured_result.fallback_section_count(),
                )
            else:
                logger.warning(
                    "[InfrastructureAgent] Structured pipeline produced validation errors "
                    "(%d errors) — falling back to ReAct loop for Dockerfile",
                    len((structured_result.validation.get("errors") or [])),
                )
        except Exception as exc:
            logger.error(
                "[InfrastructureAgent] Structured pipeline raised an exception: %s — "
                "falling back to ReAct loop",
                exc,
            )

        # ── 3. RAG retrieval for ReAct loop (Qdrant → ChromaDB fallback) ─────
        # RAG is best-effort enrichment: a vector-store outage must NOT fail the
        # Docker phase. Degrade to an empty (disabled) retrieval on any error.
        artifact_keys = self._requested_artifact_keys(mapped_context)
        try:
            qdrant_result = self._rag_pipeline.retrieve_for_agent(mapped_context, artifact_keys)
            rag_result = (
                qdrant_result
                if qdrant_result.get("available")
                else self.template_retrieval.retrieve_for_context(mapped_context, artifact_keys)
            )
        except Exception as exc:
            logger.warning(
                "[InfrastructureAgent] RAG retrieval failed (%s) — continuing without templates",
                exc,
            )
            qdrant_result = {"available": False}
            rag_result = {
                "enabled": False,
                "available": False,
                "reason": "rag_error",
                "retrievals": {},
                "template_ids": [],
            }

        # ── 4. Build ReAct loop prompt ────────────────────────────────────────
        compact_plan = self._compact_plan(plan)
        compact_context = self._compact_mapped_context(mapped_context)
        compact_rag = self._compact_rag_result(rag_result)
        compact_fallback = self._compact_fallback_hints(fallback_artifacts)

        qdrant_context_block = ""
        if qdrant_result.get("available"):
            all_results = [
                r
                for retrieval in qdrant_result.get("retrievals", {}).values()
                for r in retrieval.get("templates", [])
            ]
            if all_results:
                qdrant_context_block = self._rag_pipeline.build_llm_prompt_with_context(
                    system_prompt="",
                    user_query=prompt,
                    rag_results=[
                        {
                            "content": t.get("content", ""),
                            "source": (t.get("metadata") or {}).get("source", ""),
                            "doc_type": (t.get("metadata") or {}).get("artifact_type", ""),
                            "score": t.get("score", 0),
                        }
                        for t in all_results[:6]
                    ],
                    max_context_chars=2000,
                )[0]

        # Hint the ReAct loop when structured Dockerfile is already good
        structured_hint = ""
        if structured_dockerfile:
            structured_hint = (
                "\n\nNOTE: A structured Dockerfile was already generated and will replace "
                "your dockerfile output. Focus on dockerignore, docker_compose, and env_example."
            )

        user_prompt = f"""
User task:
{prompt}

Execution plan:
{compact_plan}

Mapped infrastructure context:
{compact_context}

Repository context is the source of truth.
Retrieved templates are guidance only — adapt to the repository.
Never copy templates blindly.
Always adapt paths, ports, commands, variables, dependencies, and build context.
Never inject real secrets.

RAG retrieval result:
{compact_rag}

Deterministic artifact hints:
{compact_fallback}

Approved artifacts to generate (Docker artifacts only):
{approved_artifacts or []}
{structured_hint}
""".strip()

        if qdrant_context_block:
            user_prompt += f"\n\nSemantic Knowledge Base Context:\n{qdrant_context_block}"

        # ── 5. ReAct loop (Tier 2 — generates all artifacts including Dockerfile fallback)
        evaluate_fn = self._make_infra_evaluator(
            mapped_context=mapped_context,
            approved_artifacts=approved_artifacts or [],
        )

        iterations_used = [0]

        def _counted_evaluate(response: Dict[str, Any]) -> List[str]:
            iterations_used[0] += 1
            return evaluate_fn(response)

        # The ReAct loop is the ONLY remaining hard LLM dependency. When every
        # provider in the fallback chain is exhausted (rate-limit / token cap /
        # invalid JSON), react_loop re-raises. We catch it here and continue with
        # an empty response: the structured Dockerfile (already produced via
        # deterministic section fallbacks if needed) plus the template-based
        # artifact builder downstream still yield a complete, valid artifact set.
        react_llm_failed = False
        try:
            response = self.react_loop(
                llm=self.llm,
                system_prompt=self.prompt_template,
                user_prompt=user_prompt,
                evaluate_fn=_counted_evaluate,
                temperature=0.2,
                max_tokens=8000,
            )
        except Exception as exc:
            react_llm_failed = True
            logger.warning(
                "[InfrastructureAgent] ReAct loop failed — LLM unavailable (%s). "
                "Degrading to deterministic Docker artifacts (non-fatal): %s",
                exc.__class__.__name__,
                exc,
            )
            response = {"artifacts": {}, "generated_artifacts": []}

        # ── 6. Inject structured Dockerfile (override ReAct result) ──────────
        if structured_dockerfile:
            response.setdefault("artifacts", {})["dockerfile"] = structured_dockerfile
            logger.info(
                "[InfrastructureAgent] Structured Dockerfile injected "
                "(blueprint=%s %d chars)",
                structured_result.blueprint_used,  # type: ignore[union-attr]
                len(structured_dockerfile),
            )

        # ── 7. Artifact selection (generated vs. fallback) ────────────────────
        artifacts = response.setdefault("artifacts", {})
        fallback_reasons: Dict[str, str] = {}
        fallback_used = False

        expectations = mapped_context.get("artifact_expectations", {})

        if expectations.get("needs_env_example"):
            artifacts["env_example"], used, reason = self._choose_best_artifact(
                artifact_key="env_example",
                generated=artifacts.get("env_example"),
                fallback=fallback_artifacts.get("env_example", ""),
                rag_result=rag_result,
            )
            fallback_used = fallback_used or used
            if reason:
                fallback_reasons["env_example"] = reason

        for key in ("dockerignore", "dockerfile"):
            artifacts[key], used, reason = self._choose_best_artifact(
                artifact_key=key,
                generated=artifacts.get(key),
                fallback=fallback_artifacts.get(key, ""),
                rag_result=rag_result,
            )
            fallback_used = fallback_used or used
            if reason:
                fallback_reasons[key] = reason

        if expectations.get("needs_docker_compose"):
            artifacts["docker_compose"], used, reason = self._choose_best_artifact(
                artifact_key="docker_compose",
                generated=artifacts.get("docker_compose"),
                fallback=fallback_artifacts.get("docker_compose", ""),
                rag_result=rag_result,
            )
            fallback_used = fallback_used or used
            if reason:
                fallback_reasons["docker_compose"] = reason

        # ── 7-pre. Template-token resolution sweep (artifact contract) ─────────
        # Every artifact that reaches persistence MUST be fully rendered. The
        # structured pipeline normally guarantees this, but a stray unresolved
        # token would otherwise block the build at the PrebuildGate. Strip any
        # residual token lines here so the persisted Dockerfile is always clean.
        artifacts, _template_sanitized, _sanitized_lines = self._sanitize_unresolved_templates(artifacts)
        if _template_sanitized:
            fallback_used = True
            fallback_reasons.setdefault("dockerfile", "template_token_sanitized")

        # ── 7-pre-b. HEALTHCHECK escape-injection repair (Docker parse safety) ─
        # A literal "\n" serialized into a HEALTHCHECK line makes `docker build`
        # fail at parse time with `unknown instruction: \nCMD`. Repair any such
        # corruption — wherever it originated (LLM section value or fallback) —
        # so the persisted Dockerfile is always parseable.
        _dockerfile_content = artifacts.get("dockerfile")
        if isinstance(_dockerfile_content, str) and _dockerfile_content.strip():
            _repaired, _hc_repairs = normalize_healthcheck(_dockerfile_content)
            if _hc_repairs:
                artifacts["dockerfile"] = _repaired
                fallback_reasons.setdefault("dockerfile", "healthcheck_escape_repaired")
                logger.warning(
                    "[InfrastructureAgent] Repaired %d HEALTHCHECK escape issue(s) "
                    "before persistence: %s",
                    len(_hc_repairs),
                    "; ".join(_hc_repairs),
                )

        # ── 7a. Dockerfile guarantee — the Docker phase MUST yield a Dockerfile ─
        # Selection above can still leave the Dockerfile empty when BOTH the LLM
        # output and the template builder produced nothing (e.g. total LLM outage
        # with a sparse context, or needs_dockerfile not flagged). Backfill it,
        # in descending order of quality, so a Dockerfile ALWAYS exists.
        if not str(artifacts.get("dockerfile") or "").strip():
            structured_raw = (
                str(structured_result.artifact or "").strip()
                if structured_result is not None
                else ""
            )
            artifacts["dockerfile"] = (
                structured_raw
                or str(fallback_artifacts.get("dockerfile") or "").strip()
                or self._minimal_safe_dockerfile(mapped_context)
            )
            fallback_used = True
            fallback_reasons.setdefault("dockerfile", "dockerfile_guarantee")
            logger.warning(
                "[InfrastructureAgent] Dockerfile guarantee engaged — no LLM "
                "Dockerfile available; backfilled deterministic Dockerfile (%d chars)",
                len(artifacts["dockerfile"]),
            )

        # ── 7b. Dockerfile-aware build-strategy reconciliation ────────────────
        # The detector ran at step 1c with only known_files. Now that the
        # Dockerfile is final, re-check whether COPY sources are
        # repo-root-relative. If they are, force STRATEGY_REPO_ROOT so the
        # downstream executor mirrors the whole repo into the build context
        # and the UI shows the correct strategy.
        final_dockerfile = artifacts.get("dockerfile") or ""
        if repo_build_ctx is not None and final_dockerfile:
            try:
                reconciled = self._strategy_detector.reconcile_with_dockerfile(
                    repo_ctx=repo_build_ctx,
                    dockerfile_content=final_dockerfile,
                    known_files=known_files or None,
                    repo_source_path=(infrastructure_context or {}).get("repo_path"),
                )
                if reconciled is not repo_build_ctx:
                    repo_build_ctx = reconciled
                    build_artifact_ctx = self._strategy_detector.build_artifact_context(
                        repo_ctx=repo_build_ctx,
                        mapped_context=mapped_context,
                    )
                    # Sync mapped_context so topology_summary + UI reflect reality.
                    new_ctx_path = repo_build_ctx.docker.context_path  # "."
                    mapped_context["build_context"] = new_ctx_path
                    mapped_context["repository_build_context"] = repo_build_ctx.to_dict()
                    mapped_context["build_artifact_context"] = build_artifact_ctx.to_dict()
                    topo = mapped_context.get("topology_summary")
                    if isinstance(topo, dict):
                        topo["build_context"] = new_ctx_path
                    logger.info(
                        "[InfrastructureAgent] Dockerfile-aware reconciliation "
                        "applied — strategy=%s context=%s",
                        repo_build_ctx.docker.strategy,
                        repo_build_ctx.docker.context_path,
                    )
            except Exception as exc:
                logger.warning(
                    "[InfrastructureAgent] Dockerfile-aware reconciliation failed: %s",
                    exc,
                )

        # ── 8. Artifact-level validation ──────────────────────────────────────
        validation_results = self.validation.validate_artifacts(artifacts)
        validation_summary = self.validation.aggregate_validation(validation_results)

        # ── 9. Assemble response ──────────────────────────────────────────────
        response["artifacts"] = artifacts
        self._strip_uploaded_env_artifact(response["artifacts"], mapped_context)
        response["context_used"] = mapped_context
        response["rag"] = {
            **compact_rag,
            "template_ids_used": rag_result.get("template_ids", []),
            "generated_with_rag": bool(rag_result.get("retrievals")),
            "fallback_used": fallback_used,
            "fallback_reasons": fallback_reasons,
        }
        response["generated_artifacts"] = self._recompute_generated_artifacts(
            response.get("generated_artifacts", []),
            artifacts,
            mapped_context,
        )
        response["requested_artifacts"] = mapped_context.get("requested_artifacts", [])
        response["artifact_targets"] = mapped_context.get("artifact_targets") or {}
        response["artifact_groups"] = self.artifact_contract.group_artifacts(
            response.get("generated_artifacts", [])
        )
        response["react_iterations"] = iterations_used[0]
        response["validation_summary"] = validation_summary

        # Phase 1: attach full structured generation trace
        if infrastructure_generation is not None:
            response["infrastructure_generation"] = infrastructure_generation

        # Infrastructure Context Grounding Layer — expose topology for UI
        response["topology_summary"] = mapped_context.get("topology_summary")
        if compose_topology is not None:
            response["compose_topology"] = mapped_context.get("compose_topology")

        # Repository build context — expose for UI debug panel and corrector
        if repo_build_ctx is not None:
            response["repository_build_context"] = repo_build_ctx.to_dict()
        if build_artifact_ctx is not None:
            response["build_artifact_context"] = build_artifact_ctx.to_dict()

        # ── 10. Phase-completion contract metadata ────────────────────────────
        # used_llm        — did the LLM contribute any content this run?
        # fallback_used   — was any deterministic fallback substituted?
        # generation_mode — coarse provenance for the UI / phase status mapping.
        structured_meta = (infrastructure_generation or {}).get("generation_metadata") or {}
        structured_llm_contributed = (
            structured_result is not None
            and structured_meta.get("dynamic_sections", 0)
            > structured_meta.get("fallback_sections", 0)
        )
        used_llm = (not react_llm_failed) or structured_llm_contributed
        fallback_used = bool(fallback_used or react_llm_failed)

        if react_llm_failed:
            generation_mode = "degraded"
        elif not used_llm:
            generation_mode = "deterministic"
        elif fallback_used:
            generation_mode = "llm_with_fallback"
        else:
            generation_mode = "llm"

        response["used_llm"] = bool(used_llm)
        response["fallback_used"] = fallback_used
        response["generation_mode"] = generation_mode
        response["template_sanitized"] = bool(_template_sanitized)
        if _sanitized_lines:
            response["template_sanitized_lines"] = _sanitized_lines

        return response

    # ── Artifact contract enforcement ─────────────────────────────────────────

    def _sanitize_unresolved_templates(
        self, artifacts: Dict[str, str]
    ) -> tuple[Dict[str, str], bool, List[str]]:
        """Strip any artifact line that still carries an unresolved template token.

        Generation should never emit ``{{ }}`` / ``{% %}`` / ``${{ }}`` style
        tokens, but if one slips through (e.g. an LLM section value that itself
        contained a placeholder), this guarantees the contract: every persisted
        artifact is fully rendered. Offending lines are removed and logged.
        Structural directives (FROM / WORKDIR / COPY / CMD) come from
        deterministic sections and never carry tokens, so removal only affects
        optional directives whose dynamic value failed to render.
        """
        try:
            from backend.app.services.artifact_generation.validators.template_artifact_validator import (
                TemplateArtifactValidator,
            )
            result = TemplateArtifactValidator().validate(artifacts)
        except Exception as exc:
            logger.warning("[InfrastructureAgent] Template sanitization scan failed: %s", exc)
            return artifacts, False, []

        if result.valid:
            return artifacts, False, []

        offending: Dict[str, set] = {}
        for issue in result.issues:
            offending.setdefault(issue.artifact, set()).add(issue.line_number)

        removed: List[str] = []
        for name, line_numbers in offending.items():
            content = artifacts.get(name) or ""
            kept_lines: List[str] = []
            for idx, line in enumerate(content.splitlines(), start=1):
                if idx in line_numbers:
                    removed.append(f"{name}:{idx}: {line.strip()}")
                    continue
                kept_lines.append(line)
            artifacts[name] = "\n".join(kept_lines)

        logger.warning(
            "[InfrastructureAgent] Sanitized %d unresolved template line(s) before "
            "persistence — artifacts: %s",
            len(removed),
            sorted(offending.keys()),
        )
        return artifacts, True, removed

    # ── Deterministic safety net ──────────────────────────────────────────────

    def _minimal_safe_dockerfile(self, mapped_context: Optional[Dict[str, Any]] = None) -> str:
        """Last-resort, dependency-free Dockerfile.

        Used only when neither the structured generator nor the template builder
        produced a Dockerfile (e.g. a total LLM outage with a sparse context).
        Intentionally minimal but build-safe: slim base, no injected secrets,
        best-effort dependency install that never hard-fails the image build.
        """
        ctx = mapped_context or {}
        main_service = ctx.get("main_service") or {}
        language = str(main_service.get("language") or "").lower()
        port = main_service.get("port") or 8000

        if language == "java":
            return "\n".join([
                "FROM eclipse-temurin:17-jre",
                "WORKDIR /app",
                "COPY . .",
                f"EXPOSE {port}",
                'CMD ["java", "-jar", "app.jar"]',
            ])
        if language in ("javascript", "typescript", "node", "nodejs"):
            return "\n".join([
                "FROM node:20-slim",
                "WORKDIR /app",
                "COPY . .",
                "RUN npm install --omit=dev || true",
                f"EXPOSE {port}",
                'CMD ["node", "server.js"]',
            ])
        # default → Python (the most common service in this platform)
        return "\n".join([
            "FROM python:3.11-slim",
            "WORKDIR /app",
            "COPY . .",
            "RUN pip install --no-cache-dir -r requirements.txt || true",
            "ENV PYTHONUNBUFFERED=1",
            f"EXPOSE {port}",
            'CMD ["python", "app.py"]',
        ])

    def _emergency_fallback_response(
        self,
        *,
        prompt: str,
        plan: Dict[str, Any],
        infrastructure_context: Optional[Dict[str, Any]],
        approved_artifacts: Optional[List[str]],
        error: Exception,
    ) -> Dict[str, Any]:
        """Build a complete, valid Docker artifact set without the LLM.

        Invoked only when the main generation pipeline raises unexpectedly. It
        re-derives a deterministic artifact set so callers always receive a
        Dockerfile and the workflow can proceed to the build step.
        """
        mapped_context: Dict[str, Any] = {}
        fallback_artifacts: Dict[str, str] = {}
        try:
            mapped_context = self.context_mapper.map(
                prompt=prompt,
                plan=plan,
                infrastructure_context=infrastructure_context,
                approved_artifacts=approved_artifacts,
            )
            fallback_artifacts = self.artifact_builder.build_fallback_artifacts(mapped_context)
        except Exception as map_exc:
            logger.warning(
                "[InfrastructureAgent] Emergency context mapping failed (%s) — "
                "using context-free minimal Dockerfile",
                map_exc,
            )

        artifacts: Dict[str, str] = {
            "dockerfile": (
                str(fallback_artifacts.get("dockerfile") or "").strip()
                or self._minimal_safe_dockerfile(mapped_context)
            )
        }
        for key in ("dockerignore", "docker_compose", "env_example"):
            value = str(fallback_artifacts.get(key) or "").strip()
            if value:
                artifacts[key] = value

        try:
            validation_summary = self.validation.aggregate_validation(
                self.validation.validate_artifacts(artifacts)
            )
        except Exception:
            validation_summary = {"status": "skipped", "issues": []}

        try:
            generated_artifacts = self._recompute_generated_artifacts(
                [], artifacts, mapped_context
            )
        except Exception:
            generated_artifacts = sorted(artifacts.keys())

        return {
            "artifacts": artifacts,
            "generated_artifacts": generated_artifacts,
            "requested_artifacts": mapped_context.get("requested_artifacts", []),
            "artifact_targets": mapped_context.get("artifact_targets") or {},
            "artifact_groups": {},
            "context_used": mapped_context,
            "rag": {
                "enabled": False,
                "available": False,
                "reason": "emergency_fallback",
                "template_ids_used": [],
                "generated_with_rag": False,
                "fallback_used": True,
                "fallback_reasons": {"dockerfile": "emergency_fallback"},
            },
            "react_iterations": 0,
            "validation_summary": validation_summary,
            "used_llm": False,
            "fallback_used": True,
            "generation_mode": "emergency_fallback",
            "generation_error": f"{error.__class__.__name__}: {error}",
        }

    # ── ReAct quality evaluator ───────────────────────────────────────────────

    def _make_infra_evaluator(
        self,
        mapped_context: Dict[str, Any],
        approved_artifacts: List[str],
    ) -> Callable[[Dict[str, Any]], List[str]]:
        expectations = mapped_context.get("artifact_expectations", {})

        def evaluate(response: Dict[str, Any]) -> List[str]:
            return self._evaluate_docker_quality(response, expectations, approved_artifacts)

        return evaluate

    def _evaluate_docker_quality(
        self,
        response: Dict[str, Any],
        expectations: Dict[str, Any],
        approved_artifacts: List[str],
    ) -> List[str]:
        """
        Docker-focused quality checks for the ReAct loop.

        When the structured pipeline already produced a valid Dockerfile,
        we skip the Dockerfile check here to avoid unnecessary retries.
        """
        issues: List[str] = []
        artifacts = (response or {}).get("artifacts") or {}

        issues.extend(self._default_evaluate(response))

        # Dockerfile: required — but skip deep check if structured pipeline handled it
        dockerfile = str(artifacts.get("dockerfile") or "").strip()
        if not dockerfile:
            issues.append("Artifact 'dockerfile' is missing or empty — it is always required")
        elif self.validation.is_generic_content(dockerfile):
            issues.append("Artifact 'dockerfile' appears to be generic/placeholder content")
        else:
            df_result = self.validation.validate_dockerfile(dockerfile)
            issues.extend(df_result.issues)

        # docker-compose: required when expected
        if expectations.get("needs_docker_compose"):
            compose = str(artifacts.get("docker_compose") or "").strip()
            if not compose:
                issues.append("Artifact 'docker_compose' is missing but was expected")
            else:
                dc_result = self.validation.validate_docker_compose(compose)
                issues.extend(dc_result.issues)

        # Generic content check for remaining Docker artifacts
        for key, content in artifacts.items():
            if key == "dockerfile":
                continue
            if content and self.validation.is_generic_content(str(content)):
                issues.append(
                    f"Artifact '{key}' appears to contain generic placeholder content"
                )

        return issues

    # ── Artifact selection helpers ────────────────────────────────────────────

    def _choose_best_artifact(
        self,
        *,
        artifact_key: str,
        generated: Optional[str],
        fallback: str,
        rag_result: Dict[str, Any],
    ) -> tuple[str, bool, Optional[str]]:
        if not str(generated or "").strip():
            return fallback, True, self._fallback_reason(artifact_key, rag_result, "empty_generation")
        if self._looks_generic(generated):  # type: ignore[arg-type]
            return fallback, True, self._fallback_reason(artifact_key, rag_result, "generic_generation")
        return generated, False, None  # type: ignore[return-value]

    def _fallback_reason(
        self,
        artifact_key: str,
        rag_result: Dict[str, Any],
        base_reason: str,
    ) -> str:
        if not rag_result.get("enabled"):
            return f"{base_reason}:rag_disabled"
        if not rag_result.get("available"):
            return f"{base_reason}:{rag_result.get('reason', 'rag_unavailable')}"
        if artifact_key not in (rag_result.get("retrievals") or {}):
            return f"{base_reason}:no_relevant_templates"
        return f"{base_reason}:template_guidance_insufficient"

    def _looks_generic(self, content: str) -> bool:
        lowered = content.lower()
        generic_markers = [
            'cmd ["python", "app.py"]',
            "env_var=example",
            "your-image:latest",
            "lorem ipsum",
        ]
        return any(marker in lowered for marker in generic_markers)

    # ── Context / prompt helpers ──────────────────────────────────────────────

    def _requested_artifact_keys(self, mapped_context: Dict[str, Any]) -> List[str]:
        """Return Docker-scoped artifact keys only."""
        expectations = mapped_context.get("artifact_expectations") or {}
        keys = ["dockerfile", "dockerignore", "docker_compose"]
        if expectations.get("needs_env_example"):
            keys.append("env_example")
        keys.append("security_notes")
        return keys

    def _recompute_generated_artifacts(
        self,
        generated_artifacts: List[str],
        artifacts: Dict[str, str],
        mapped_context: Dict[str, Any],
    ) -> List[str]:
        if mapped_context.get("env_source_of_truth") == "uploaded":
            artifacts.pop("env_example", None)
        artifact_targets = mapped_context.get("artifact_targets") or {}
        key_to_file = {
            "dockerfile": artifact_targets.get("dockerfile") or "Dockerfile",
            "dockerignore": ".dockerignore",
            "docker_compose": artifact_targets.get("docker_compose") or "docker-compose.yml",
            "env_example": (
                (artifact_targets.get("env_files") or [".env.example"])[0]
                if artifact_targets.get("env_files")
                else ".env.example"
            ),
            "build_script": "scripts/build.sh",
            "deploy_script": "scripts/deploy.sh",
            "security_scan_config": ".github/workflows/security-scan.yml",
            "readme_snippet": "README_infrastructure.md",
        }
        generated = {
            name
            for name in (generated_artifacts or [])
            if name not in key_to_file.values()
        }
        for key, file_name in key_to_file.items():
            if str(artifacts.get(key) or "").strip():
                generated.add(file_name)
        return sorted(generated)

    def _strip_uploaded_env_artifact(
        self, artifacts: Dict[str, str], mapped_context: Dict[str, Any]
    ) -> None:
        if mapped_context.get("env_source_of_truth") != "uploaded":
            return
        artifacts.pop("env_example", None)

