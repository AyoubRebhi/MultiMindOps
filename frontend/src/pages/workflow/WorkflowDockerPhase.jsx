import { useState } from 'react';
import { Link } from 'react-router-dom';
import WorkflowTimeline from '@/components/workflow/WorkflowTimeline';
import WorkflowPhaseHeader from '@/components/workflow/WorkflowPhaseHeader';
import EmptyState from '@/components/common/EmptyState';
import ErrorState from '@/components/common/ErrorState';
import Skeleton from '@/components/common/Skeleton';
import DockerReviewBuildSection from '@/components/workflow/docker/DockerReviewBuildSection';
import { useDockerPhase } from '@/hooks/useWorkflowRun';
import { useToast } from '@/hooks/useToast';
import { workflowApi } from '@/services/api/workflowApi';

/**
 * WorkflowDockerPhase — the third executable workflow phase, backed by REAL
 * data. ONE read (GET .../docker) feeds the whole surface: the generated
 * Dockerfile, the generation metadata the InfrastructureAgent detected, the
 * validation findings, the Docker corrector's analysis (when a build failed),
 * a side-by-side original↔corrected diff, and the approved artifact later
 * phases consume. Generation itself is triggered through the backend
 * (POST .../phases/DOCKER → InfrastructureAgent, GPT-5-mini → Groq); the
 * frontend never mutates workflow state or fabricates a Dockerfile.
 *
 * @param {{ workflowId: string, workflow: object, onAdvance?: () => void }} props
 */
export default function WorkflowDockerPhase({ workflowId, workflow, onAdvance }) {
  const projectId = workflow?.projectId;
  const toast = useToast();
  const { data, loading, error, refetch } = useDockerPhase(projectId, workflowId);
  const [generating, setGenerating] = useState(false);
  const [proceeding, setProceeding] = useState(false);

  async function handleGenerate() {
    if (!projectId || generating) return;
    setGenerating(true);
    try {
      await workflowApi.runDockerPhase(projectId, workflowId);
      toast.success('Dockerfile generated by the Docker agent.');
      await refetch();
      onAdvance?.();
    } catch (e) {
      toast.error(e?.message || 'Could not generate the Dockerfile. Please try again.');
    } finally {
      setGenerating(false);
    }
  }

  // Advance to the Terraform Generation phase. Runs TERRAFORM_GENERATION on the
  // backend (inline), then refetches the workflow — its current_phase becomes
  // TERRAFORM_GENERATION, so the resume router (WorkflowRunPage) flips to the
  // Terraform surface, which shows the freshly generated .tf files.
  async function handleProceedToTerraform() {
    if (!projectId || proceeding) return;
    setProceeding(true);
    try {
      await workflowApi.runTerraformPhase(projectId, workflowId, 'TERRAFORM_GENERATION');
      toast.success('Terraform generation started.');
      onAdvance?.();
    } catch (e) {
      toast.error(e?.message || 'Could not start Terraform generation. Please try again.');
    } finally {
      setProceeding(false);
    }
  }

  /* ── Hard transport failure ──────────────────────────────────────────────── */
  if (error && !data) {
    return (
      <DockerShell workflow={workflow} status="failed">
        <ErrorState
          title="Couldn't load the Docker phase"
          message={error.message}
          onRetry={refetch}
        />
      </DockerShell>
    );
  }

  /* ── First load ──────────────────────────────────────────────────────────── */
  if (loading && !data) {
    return (
      <DockerShell workflow={workflow} status={workflow?.status}>
        <DockerSkeletons />
      </DockerShell>
    );
  }

  /* ── Not generated yet → offer to run the phase ──────────────────────────── */
  if (!data || !data.generated) {
    return (
      <DockerShell workflow={workflow} status="running">
        <NotGenerated
          projectId={projectId}
          generating={generating}
          onGenerate={handleGenerate}
        />
      </DockerShell>
    );
  }

  const docComplete =
    data.dockerPhaseStatus === 'completed' ||
    data.dockerPhaseStatus === 'completed_with_fallback';

  return (
    <DockerShell
      workflow={workflow}
      status={docComplete ? 'completed' : workflow?.status}
      actions={
        <div className="d-flex gap-2">
          <button
            type="button"
            className="boc btn px-3 py-2"
            style={{ fontSize: '.82rem' }}
            disabled={generating}
            onClick={handleGenerate}
          >
            {generating ? <span className="spinner me-2" /> : <i className="fa-solid fa-rotate-right me-2" />}
            Regenerate
          </button>
          {docComplete && (
            <button
              type="button"
              className="bgrd btn px-3 py-2"
              style={{ fontSize: '.82rem' }}
              disabled={proceeding}
              onClick={handleProceedToTerraform}
            >
              {proceeding ? (
                <><span className="spinner me-2" />Starting Terraform…</>
              ) : (
                <><i className="fa-solid fa-cubes me-2" />Proceed to Terraform Generation</>
              )}
            </button>
          )}
        </div>
      }
    >
      {/* Review → Approve → Build → Logs → Corrector → Fix → Rebuild, all wired
          to existing backend endpoints (see DockerReviewBuildSection). */}
      <DockerReviewBuildSection
        projectId={projectId}
        taskId={data.taskId}
        data={data}
        onPhaseRefetch={refetch}
      />
    </DockerShell>
  );
}

/* ── Layout shell: timeline + phase header + content ───────────────────────── */

function DockerShell({ status, actions, children }) {
  const dockerState =
    status === 'completed' ? 'completed' : status === 'failed' ? 'failed' : 'running';
  return (
    <>
      <WorkflowTimeline
        current="docker"
        navigable={false}
        statuses={{ analysis: 'completed', planning: 'completed', docker: dockerState }}
      />
      <WorkflowPhaseHeader
        icon="fa-docker"
        brand
        eyebrow="Phase 3 · Container Build"
        title="Docker Generation"
        subtitle="Review the AI-generated Dockerfile, its validation findings and any auto-corrections before it's used to build the image."
        status={status}
        actions={actions}
      />
      {children}
    </>
  );
}

/* ── States ────────────────────────────────────────────────────────────────── */

function NotGenerated({ projectId, generating, onGenerate }) {
  return (
    <EmptyState
      icon="fa-docker"
      title="No Dockerfile generated yet"
      message="A plan is selected — generate the container definition for this project. The Docker agent (GPT-5-mini, with a Groq fallback) detects the runtime, picks a base image and writes a build-ready Dockerfile."
      action={
        <div className="d-flex gap-2 justify-content-center">
          <button
            type="button"
            className="bgrd btn px-4 py-2"
            style={{ fontSize: '.85rem' }}
            disabled={generating}
            onClick={onGenerate}
          >
            {generating ? (
              <><span className="spinner me-2" />Generating…</>
            ) : (
              <><i className="fa-brands fa-docker me-2" />Generate Dockerfile</>
            )}
          </button>
          {projectId && (
            <Link to={`/projects/${projectId}`} className="boc btn px-3 py-2" style={{ fontSize: '.85rem' }}>
              <i className="fa-solid fa-folder-open me-2" />
              Open project
            </Link>
          )}
        </div>
      }
    />
  );
}

