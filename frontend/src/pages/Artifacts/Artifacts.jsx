import { useMemo, useState } from 'react';
import ContentContainer from '@/components/layout/ContentContainer';
import PageHeader from '@/components/layout/PageHeader';
import ArtifactCard from '@/components/artifacts/ArtifactCard';
import EmptyState from '@/components/common/EmptyState';
import LoadingSpinner from '@/components/common/LoadingSpinner';
import { useArtifacts } from '@/hooks/useArtifacts';
import { ARTIFACT_TYPES } from '@/utils/constants';

/** Artifacts — every generated artifact across the workspace (DevOps view). */
export default function Artifacts() {
  const { data: artifacts, loading } = useArtifacts();
  const [type, setType] = useState('all');

  const types = useMemo(() => {
    const present = new Set((artifacts || []).map((a) => a.type));
    return ['all', ...Object.keys(ARTIFACT_TYPES).filter((t) => present.has(t))];
  }, [artifacts]);

  const filtered = (artifacts || []).filter((a) => type === 'all' || a.type === type);

  return (
    <ContentContainer>
      <PageHeader
        title="Artifacts"
        subtitle="Dockerfiles, Terraform, Kubernetes and Helm artifacts generated by the AI agents."
        breadcrumbs={[{ label: 'Artifacts' }]}
      />

      <div className="d-flex flex-wrap gap-2 mb-4">
        {types.map((t) => {
          const meta = ARTIFACT_TYPES[t];
          const active = type === t;
          return (
            <button
              key={t}
              className="boc btn px-3 py-1"
              style={{
                fontSize: '.8rem',
                borderRadius: 10,
                background: active ? 'rgba(139,92,246,.15)' : 'var(--sf)',
                color: active ? '#a78bfa' : 'var(--tx2)',
                borderColor: active ? 'rgba(139,92,246,.3)' : 'var(--bd)',
              }}
              onClick={() => setType(t)}
            >
              {meta ? (
                <>
                  <i className={`${meta.brand ? 'fa-brands' : 'fa-solid'} ${meta.icon} me-1`} />
                  {meta.label}
                </>
              ) : (
                'All'
              )}
            </button>
          );
        })}
      </div>

      {loading && !artifacts?.length ? (
        <LoadingSpinner center label="Loading artifacts…" />
      ) : filtered.length === 0 ? (
        <EmptyState icon="fa-file-code" title="No artifacts" message="Run a workflow to generate artifacts." />
      ) : (
        <div className="row g-3">
          {filtered.map((art) => (
            <div className="col-lg-6" key={art.id}>
              <ArtifactCard artifact={art} />
            </div>
          ))}
        </div>
      )}
    </ContentContainer>
  );
}
