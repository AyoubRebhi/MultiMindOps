from langgraph.graph import START, END, StateGraph

from agents.base_agent import BaseAgent
from agents.infrastructure_agent import InfrastructureAgent
from agents.planner_agent import PlannerAgent
from agents.state import OrchestratorState


class OrchestratorAgent(BaseAgent):
    def __init__(self):
        super().__init__(name="OrchestratorAgent")
        self.planner = PlannerAgent()
        self.infrastructure = InfrastructureAgent()
        self.graph = self._build_graph()

    def _initialize(self, state: OrchestratorState) -> OrchestratorState:
        logs = state.get("logs", [])
        logs.append({"step": "orchestrator", "message": "Workflow started"})
        return {**state, "status": "in_progress", "logs": logs}

    def _planner_node(self, state: OrchestratorState) -> OrchestratorState:
        plan = self.planner.run(state["prompt"])
        logs = state.get("logs", [])
        logs.append({"step": "planner", "message": "Plan generated by LLM"})
        return {**state, "plan": plan, "logs": logs}

    def _infrastructure_node(self, state: OrchestratorState) -> OrchestratorState:
        infra = self.infrastructure.run(state["prompt"], state["plan"])
        logs = state.get("logs", [])
        logs.append({"step": "infrastructure", "message": "Infrastructure artifacts generated"})
        return {**state, "infra": infra, "logs": logs}

    def _finalize(self, state: OrchestratorState) -> OrchestratorState:
        result = {
            "agent": "OrchestratorAgent",
            "status": "success",
            "plan": state.get("plan"),
            "infra": state.get("infra"),
        }
        logs = state.get("logs", [])
        logs.append({"step": "completed", "message": "Workflow completed"})
        return {**state, "status": "completed", "result": result, "logs": logs}

    def _build_graph(self):
        graph = StateGraph(OrchestratorState)
        graph.add_node("initialize", self._initialize)
        graph.add_node("planner", self._planner_node)
        graph.add_node("infrastructure", self._infrastructure_node)
        graph.add_node("finalize", self._finalize)

        graph.add_edge(START, "initialize")
        graph.add_edge("initialize", "planner")
        graph.add_edge("planner", "infrastructure")
        graph.add_edge("infrastructure", "finalize")
        graph.add_edge("finalize", END)

        return graph.compile()

    def run(self, prompt: str):
        return self.graph.invoke({
            "prompt": prompt,
            "status": "pending",
            "logs": [],
            "plan": None,
            "infra": None,
            "result": None,
            "error_message": None,
        })